"""Build the M4 proxy-labeled mini-corpus manifest (deterministic).

Three groups (plan §M4, §I adversarial probe):
  * **H** — human-student, presumed-experiential: PERSUADE persuasive essays
    (``realbenpope/PERSUADE_manageable``), first 25 with >=120 words in CSV order.
    Texts are NOT committed (dataset redistribution hygiene, mirrors SCoCESLE
    local-only handling) — cached to a gitignored ``_persuade_cache.jsonl`` and
    referenced by ``essay_id`` + ``sha256`` in the manifest.
  * **A** — AI-generic: first 20 committed ``ai_gpt_5_6_user_NN`` cases under
    ``poc/calibration/authorship_cases`` (referenced by committed path).
  * **G** — GAMING (fabricated specifics): committed synthetic adversarial
    fixtures under ``eval/gaming_cases/`` (generated by generate_gaming_cases.py).

The manifest records numbers + provenance only; the harness (run_eval.py)
resolves each doc's text via ``resolve_text``. Deterministic: same corpus in,
byte-identical manifest out (sorted, fixed selection order).
"""
from __future__ import annotations

import glob
import hashlib
import json
import os
from typing import Any, Optional

MANIFEST_VERSION = "cg-m4-1"
_HERE = os.path.dirname(os.path.abspath(__file__))
_POC_ROOT = os.path.abspath(os.path.join(_HERE, "..", ".."))
_AUTH_CASES = os.path.join(_POC_ROOT, "calibration", "authorship_cases")
_GAMING_DIR = os.path.join(_HERE, "gaming_cases")
_PERSUADE_CACHE = os.path.join(_HERE, "_persuade_cache.jsonl")
_MANIFEST_PATH = os.path.join(_HERE, "corpus_manifest.json")

PERSUADE_REPO = "realbenpope/PERSUADE_manageable"
PERSUADE_FILE = "persuade_full_text.csv"

H_COUNT = 25
A_COUNT = 20
H_MIN_WORDS = 120
A_PREFIX = "ai_gpt_5_6_user_"  # gpt-5.6 essays (non-casual), sorted, first A_COUNT


def _sha256(text: str) -> str:
    return hashlib.sha256((text or "").encode("utf-8")).hexdigest()


def _words(text: str) -> int:
    return len((text or "").split())


# ── Group H — PERSUADE ───────────────────────────────────────────────────────
def _persuade_csv_path() -> Optional[str]:
    hits = glob.glob(os.path.expanduser(
        "~/.cache/huggingface/hub/datasets--realbenpope--PERSUADE_manageable/"
        "snapshots/*/persuade_full_text.csv"))
    return sorted(hits)[0] if hits else None


def _download_persuade() -> Optional[str]:
    path = _persuade_csv_path()
    if path:
        return path
    try:  # lazy — hf CLI/lib is heavy and optional
        from huggingface_hub import hf_hub_download
        hf_hub_download(PERSUADE_REPO, PERSUADE_FILE, repo_type="dataset")
    except Exception:
        return None
    return _persuade_csv_path()


def select_persuade(n: int = H_COUNT, min_words: int = H_MIN_WORDS) -> list[dict[str, Any]]:
    """First ``n`` PERSUADE essays (CSV order) with >= ``min_words`` words.

    Deterministic: pandas preserves CSV row order; selection is the first n
    passing the word floor. Returns ``[{essay_id, words, sha256, text}]``.
    """
    path = _download_persuade()
    if not path:
        raise RuntimeError("PERSUADE CSV unavailable (hf download failed)")
    import pandas as pd
    df = pd.read_csv(path)
    out: list[dict[str, Any]] = []
    for _, row in df.iterrows():
        text = str(row["full_text"] or "").strip()
        if _words(text) < min_words:
            continue
        out.append({
            "essay_id": str(row["essay_id_comp"]),
            "words": _words(text),
            "sha256": _sha256(text),
            "text": text,
        })
        if len(out) >= n:
            break
    if len(out) < n:
        raise RuntimeError("PERSUADE yielded only %d essays >= %d words" % (len(out), min_words))
    return out


def write_persuade_cache(rows: list[dict[str, Any]]) -> None:
    with open(_PERSUADE_CACHE, "w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")


def load_persuade_cache() -> dict[str, dict[str, Any]]:
    if not os.path.exists(_PERSUADE_CACHE):
        return {}
    out: dict[str, dict[str, Any]] = {}
    with open(_PERSUADE_CACHE, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            out[r["essay_id"]] = r
    return out


# ── Group A — committed AI cases ─────────────────────────────────────────────
def select_group_a(n: int = A_COUNT) -> list[dict[str, Any]]:
    names = sorted(
        os.path.basename(p) for p in glob.glob(os.path.join(_AUTH_CASES, A_PREFIX + "*.json"))
        if "casual" not in os.path.basename(p)
    )[:n]
    out: list[dict[str, Any]] = []
    for name in names:
        with open(os.path.join(_AUTH_CASES, name), encoding="utf-8") as fh:
            case = json.load(fh)
        text = str(case.get("text") or "").strip()
        out.append({
            "path": os.path.join("poc", "calibration", "authorship_cases", name),
            "source": str(case.get("source") or "unknown"),
            "words": _words(text),
            "sha256": _sha256(text),
        })
    return out


# ── Group G — committed gaming fixtures ──────────────────────────────────────
def collect_gaming() -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for p in sorted(glob.glob(os.path.join(_GAMING_DIR, "*.json"))):
        with open(p, encoding="utf-8") as fh:
            case = json.load(fh)
        text = str(case.get("text") or "").strip()
        out.append({
            "path": os.path.join("poc", "claim_graph", "eval", "gaming_cases", os.path.basename(p)),
            "source": str(case.get("source") or "gpt-oss:gaming-synthetic"),
            "words": _words(text),
            "sha256": _sha256(text),
        })
    return out


# ── Manifest assembly ────────────────────────────────────────────────────────
def build_manifest(persuade_rows: list[dict[str, Any]]) -> dict[str, Any]:
    docs: list[dict[str, Any]] = []
    for i, r in enumerate(persuade_rows):
        docs.append({
            "group": "H", "doc_id": "H_%02d" % i,
            "label": "human_student_persuade",
            "source": PERSUADE_REPO, "essay_id": r["essay_id"],
            "words": r["words"], "sha256": r["sha256"],
            "text_ref": {"kind": "persuade_cache", "key": r["essay_id"]},
        })
    for i, r in enumerate(select_group_a()):
        docs.append({
            "group": "A", "doc_id": "A_%02d" % i, "label": "ai_generic",
            "source": r["source"], "path": r["path"],
            "words": r["words"], "sha256": r["sha256"],
            "text_ref": {"kind": "case_json", "path": r["path"]},
        })
    for i, r in enumerate(collect_gaming()):
        docs.append({
            "group": "G", "doc_id": "G_%02d" % i, "label": "gaming_fabricated_specifics",
            "source": r["source"], "path": r["path"],
            "words": r["words"], "sha256": r["sha256"],
            "text_ref": {"kind": "case_json", "path": r["path"]},
        })
    return {
        "manifest_version": MANIFEST_VERSION,
        "groups": {
            "H": {"label": "human_student_persuade", "presumed": "experiential/grounded",
                  "source": PERSUADE_REPO, "note": "texts local-only, referenced by essay_id"},
            "A": {"label": "ai_generic", "presumed": "thin/generic", "source": A_PREFIX + "*"},
            "G": {"label": "gaming_fabricated_specifics",
                  "presumed": "§I adversarial: fabricated specifics/fake studies/synthetic revisions",
                  "source": "gpt-oss gateway (synthetic)"},
        },
        "counts": {g: sum(1 for d in docs if d["group"] == g) for g in ("H", "A", "G")},
        "docs": docs,
    }


def resolve_text(doc: dict[str, Any], persuade_cache: Optional[dict[str, dict[str, Any]]] = None) -> str:
    """Resolve a manifest doc's text (used by run_eval.py)."""
    ref = doc.get("text_ref") or {}
    if ref.get("kind") == "persuade_cache":
        cache = persuade_cache if persuade_cache is not None else load_persuade_cache()
        row = cache.get(ref.get("key"))
        if row is None:
            raise RuntimeError("PERSUADE text %s not in cache; rebuild manifest" % ref.get("key"))
        return str(row["text"])
    if ref.get("kind") == "case_json":
        path = ref["path"] if os.path.isabs(ref["path"]) \
            else os.path.abspath(os.path.join(_POC_ROOT, "..", ref["path"]))
        with open(path, encoding="utf-8") as fh:
            return str(json.load(fh).get("text") or "")
    raise RuntimeError("unknown text_ref kind: %r" % ref.get("kind"))


def main() -> None:
    rows = select_persuade()
    write_persuade_cache(rows)
    manifest = build_manifest(rows)
    with open(_MANIFEST_PATH, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print("manifest: %s" % _MANIFEST_PATH)
    print("counts: %s" % manifest["counts"])


if __name__ == "__main__":
    main()
